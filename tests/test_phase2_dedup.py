def test_overall_score_weights_match_spec(tmp_path):
    """The weights are 2.0 (correctness) + 1.5 (completeness) +
    1.0 + 1.0 = 5.5 max. A perfect language hits exactly that."""
    spec_dir = tmp_path / "lang"
    _write_spec(spec_dir, copy.deepcopy(_BASE_SPEC))
    perfect = _make_report(
        slot_id="perfect", lang_dir=spec_dir,
        correctness_passed=True,
        distinctiveness=1.0, coherence=1.0, completeness=1.0,
    )
    assert _overall_score(perfect) == 2.0 + 1.5 + 1.0 + 1.0
    # Failing-correctness with everything else max → 0 + 1.5 + 1 + 1 = 3.5
    failing = _make_report(
        slot_id="failing", lang_dir=spec_dir,
        correctness_passed=False,
        distinctiveness=1.0, coherence=1.0, completeness=1.0,
    )
    assert _overall_score(failing) == 0.0 + 1.5 + 1.0 + 1.0
