def test_dedup_summary_aggregates_correctly(tmp_path):
    a_dir = tmp_path / "a"; b_dir = tmp_path / "b"
    c_dir = tmp_path / "c"; d_dir = tmp_path / "d"
    spec_ab = copy.deepcopy(_BASE_SPEC)
    spec_cd = copy.deepcopy(_BASE_SPEC)
    spec_cd["customization"] = dict(spec_cd["customization"])
    spec_cd["customization"]["theme"] = "pirate"
    _write_spec(a_dir, spec_ab); _write_spec(b_dir, spec_ab)
    _write_spec(c_dir, spec_cd); _write_spec(d_dir, spec_cd)
    reports = [
        _make_report(slot_id="a", lang_dir=a_dir),
        _make_report(slot_id="b", lang_dir=b_dir),
        _make_report(slot_id="c", lang_dir=c_dir),
        _make_report(slot_id="d", lang_dir=d_dir),
    ]
    results = dedup_languages(reports)
    assert len(results) == 2  # two distinct fingerprints, each with 2 members
    summary = dedup_summary(results)
    assert summary["total_reports"] == 4
    assert summary["unique_languages"] == 2
    assert summary["duplicates_collapsed"] == 2
    assert summary["largest_group_size"] == 2


def test_dedup_summary_empty():
    summary = dedup_summary([])
    assert summary == {
        "total_reports": 0, "unique_languages": 0,
        "duplicates_collapsed": 0, "largest_group_size": 0,
    }


