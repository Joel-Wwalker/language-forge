def test_dedup_groups_two_clones(tmp_path):
    a_dir = tmp_path / "a"
    b_dir = tmp_path / "b"
    spec_a = copy.deepcopy(_BASE_SPEC); spec_a["lang_name"] = "a"
    spec_b = copy.deepcopy(_BASE_SPEC); spec_b["lang_name"] = "b"
    _write_spec(a_dir, spec_a); _write_spec(b_dir, spec_b)
    reports = [
        _make_report(slot_id="slot_a", lang_dir=a_dir),
        _make_report(slot_id="slot_b", lang_dir=b_dir),
    ]
    results = dedup_languages(reports)
    assert len(results) == 1
    assert len(results[0].duplicate_slot_ids) == 1


def test_dedup_keeps_distinct_languages_separate(tmp_path):
    a_dir = tmp_path / "a"
    b_dir = tmp_path / "b"
    spec_a = copy.deepcopy(_BASE_SPEC)
    spec_b = copy.deepcopy(_BASE_SPEC)
    spec_b["customization"] = dict(spec_b["customization"])
    spec_b["customization"]["theme"] = "pirate"
    _write_spec(a_dir, spec_a); _write_spec(b_dir, spec_b)
    reports = [
        _make_report(slot_id="slot_a", lang_dir=a_dir),
        _make_report(slot_id="slot_b", lang_dir=b_dir),
    ]
    results = dedup_languages(reports)
    assert len(results) == 2
    assert all(not r.duplicate_slot_ids for r in results)


def test_dedup_picks_highest_scoring_as_representative(tmp_path):
    """Two duplicates: the one with higher overall_score wins."""
    a_dir = tmp_path / "low_quality"
    b_dir = tmp_path / "high_quality"
    spec_a = copy.deepcopy(_BASE_SPEC); spec_a["lang_name"] = "a"
    spec_b = copy.deepcopy(_BASE_SPEC); spec_b["lang_name"] = "b"
    _write_spec(a_dir, spec_a); _write_spec(b_dir, spec_b)
    reports = [
        _make_report(slot_id="slot_low", lang_dir=a_dir,
                     distinctiveness=0.1, coherence=0.5,
                     completeness=0.85),
        _make_report(slot_id="slot_high", lang_dir=b_dir,
                     distinctiveness=0.9, coherence=1.0,
                     completeness=1.0),
    ]
    results = dedup_languages(reports)
    assert len(results) == 1
    assert results[0].representative_slot_id == "slot_high"
    assert "slot_low" in results[0].duplicate_slot_ids


def test_dedup_three_way_collapse(tmp_path):
    """Three duplicates collapse to one + two."""
    a_dir = tmp_path / "a"; b_dir = tmp_path / "b"; c_dir = tmp_path / "c"
    spec = copy.deepcopy(_BASE_SPEC)
    for d, name in [(a_dir, "a"), (b_dir, "b"), (c_dir, "c")]:
        s = copy.deepcopy(spec); s["lang_name"] = name
        _write_spec(d, s)
    reports = [
        _make_report(slot_id="slot_a", lang_dir=a_dir, distinctiveness=0.5),
        _make_report(slot_id="slot_b", lang_dir=b_dir, distinctiveness=0.9),
        _make_report(slot_id="slot_c", lang_dir=c_dir, distinctiveness=0.3),
    ]
    results = dedup_languages(reports)
    assert len(results) == 1
    assert results[0].representative_slot_id == "slot_b"
    assert sorted(results[0].duplicate_slot_ids) == ["slot_a", "slot_c"]


def test_dedup_correctness_passing_beats_failing(tmp_path):
    """A passing-correctness duplicate beats a failing-correctness one
    even when the failing one would otherwise score higher on graded
    dimensions."""
    a_dir = tmp_path / "a"; b_dir = tmp_path / "b"
    spec = copy.deepcopy(_BASE_SPEC)
    _write_spec(a_dir, copy.deepcopy(spec))
    _write_spec(b_dir, copy.deepcopy(spec))
    reports = [
        _make_report(slot_id="slot_broken_high",
                     lang_dir=a_dir,
                     correctness_passed=False,
                     distinctiveness=0.9, coherence=1.0,
                     completeness=1.0),
        _make_report(slot_id="slot_working_low",
                     lang_dir=b_dir,
                     correctness_passed=True,
                     distinctiveness=0.1, coherence=0.5,
                     completeness=0.9),
    ]
    results = dedup_languages(reports)
    assert len(results) == 1
    assert results[0].representative_slot_id == "slot_working_low"


def test_dedup_tie_break_by_slot_id(tmp_path):
    """Equal scores → lower slot_id alphabetically wins. Pins
    deterministic output ordering."""
    a_dir = tmp_path / "a"; b_dir = tmp_path / "b"
    spec = copy.deepcopy(_BASE_SPEC)
    _write_spec(a_dir, copy.deepcopy(spec))
    _write_spec(b_dir, copy.deepcopy(spec))
    reports = [
        _make_report(slot_id="zzz", lang_dir=a_dir,
                     distinctiveness=0.5, coherence=0.5, completeness=1.0),
        _make_report(slot_id="aaa", lang_dir=b_dir,
                     distinctiveness=0.5, coherence=0.5, completeness=1.0),
    ]
    results = dedup_languages(reports)
    assert results[0].representative_slot_id == "aaa"


def test_dedup_empty_input():
    assert dedup_languages([]) == []


def test_dedup_idempotent(tmp_path):
    """Same input twice → same output."""
    a_dir = tmp_path / "a"; b_dir = tmp_path / "b"; c_dir = tmp_path / "c"
    spec_ab = copy.deepcopy(_BASE_SPEC)
    spec_c = copy.deepcopy(_BASE_SPEC)
    spec_c["customization"] = dict(spec_c["customization"])
    spec_c["customization"]["theme"] = "pirate"
    _write_spec(a_dir, spec_ab); _write_spec(b_dir, spec_ab)
    _write_spec(c_dir, spec_c)
    reports = [
        _make_report(slot_id="a", lang_dir=a_dir),
        _make_report(slot_id="b", lang_dir=b_dir),
        _make_report(slot_id="c", lang_dir=c_dir),
    ]
    r1 = dedup_languages(reports)
    r2 = dedup_languages(reports)
    assert [result_to_dict(x) for x in r1] == [result_to_dict(x) for x in r2]


