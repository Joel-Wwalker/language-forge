def test_fingerprint_equal_for_specs_differing_only_in_lang_name(tmp_path):
    """Two slots whose resolved specs differ only in lang_name and
    display_name MUST hash identically — that's the entire point of
    dedup. (The resolver cache key uses the same approach.)"""
    a_dir = tmp_path / "a"
    b_dir = tmp_path / "b"
    spec_a = copy.deepcopy(_BASE_SPEC)
    spec_a["lang_name"] = "alpha"
    spec_a["display_name"] = "alpha"
    spec_b = copy.deepcopy(_BASE_SPEC)
    spec_b["lang_name"] = "beta"
    spec_b["display_name"] = "beta"
    _write_spec(a_dir, spec_a)
    _write_spec(b_dir, spec_b)
    r_a = _make_report(slot_id="a", lang_dir=a_dir)
    r_b = _make_report(slot_id="b", lang_dir=b_dir)
    assert fingerprint(r_a) == fingerprint(r_b)


def test_fingerprint_differs_on_keyword_overrides(tmp_path):
    a_dir = tmp_path / "a"
    b_dir = tmp_path / "b"
    spec_a = copy.deepcopy(_BASE_SPEC)
    spec_b = copy.deepcopy(_BASE_SPEC)
    spec_b["customization"]["keyword_overrides"] = {"var": "loot"}
    _write_spec(a_dir, spec_a)
    _write_spec(b_dir, spec_b)
    r_a = _make_report(slot_id="a", lang_dir=a_dir)
    r_b = _make_report(slot_id="b", lang_dir=b_dir)
    assert fingerprint(r_a) != fingerprint(r_b)


def test_fingerprint_differs_on_options(tmp_path):
    a_dir = tmp_path / "a"
    b_dir = tmp_path / "b"
    spec_a = copy.deepcopy(_BASE_SPEC)
    spec_b = copy.deepcopy(_BASE_SPEC)
    spec_b["options"] = dict(spec_b["options"])
    spec_b["options"]["memory"] = "refcount"
    _write_spec(a_dir, spec_a)
    _write_spec(b_dir, spec_b)
    r_a = _make_report(slot_id="a", lang_dir=a_dir)
    r_b = _make_report(slot_id="b", lang_dir=b_dir)
