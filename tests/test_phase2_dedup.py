"""Phase 2 Stage B — dedup tests.

Pins:
  - Two languages with identical specs and different slot_ids get grouped.
  - Two languages with mostly-identical specs but one different
    customization field do NOT get grouped.
  - The representative is the one with the highest quality score.
  - Three-way duplicates collapse to one representative + two duplicates.
  - Empty input returns empty output.
  - Same input twice → same output (idempotent).
"""
from __future__ import annotations

import json
import copy
from pathlib import Path

import pytest

from forge.catalog.dedup import (
    dedup_languages,
    dedup_summary,
    fingerprint,
    result_to_dict,
    _overall_score,
)
from forge.catalog.quality import (
    CompletenessResult,
    CorrectnessResult,
    CoherenceResult,
    DistinctivenessResult,
    QualityReport,
)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _write_spec(lang_dir: Path, spec: dict) -> None:
    lang_dir.mkdir(parents=True, exist_ok=True)
    (lang_dir / "resolved_spec.json").write_text(
        json.dumps(spec, indent=2), encoding="utf-8"
    )


def _make_report(*, slot_id: str, lang_dir: Path,
                 correctness_passed: bool = True,
                 distinctiveness: float = 0.5,
                 coherence: float = 1.0,
                 completeness: float = 1.0,
                 family: str = "c_like") -> QualityReport:
    """Build a synthetic QualityReport for testing."""
    return QualityReport(
        slot_id=slot_id,
        lang_dir=str(lang_dir.resolve()),
        family=family,
        pipeline_path="templated",
        correctness=CorrectnessResult(
            passed=correctness_passed,
            canonical_tests={"passed": 8 if correctness_passed else 0,
                             "total": 8, "pass_rate": 1.0,
                             "source": "fixture"},
            kata_pack=None,
            repl={"repl_html_ok": True, "compile_exit_code": 0,
                  "launches": True},
            failures=[] if correctness_passed else ["canonical: 0/8"],
            skips=[],
        ),
        distinctiveness=DistinctivenessResult(
            score=distinctiveness, surface=distinctiveness,
            persona=distinctiveness, variety=distinctiveness, notes=[],
        ),
        coherence=CoherenceResult(
            score=coherence,
            overrides_unique=True, readme_mentions_name=True,
            readme_length_ok=True, stdlib_naming_consistent=True,
            notes=[],
        ),
        completeness=CompletenessResult(
            score=completeness, present=[], missing=[]
        ),
        overall_passed=correctness_passed and completeness >= 0.8,
        rejection_reason=None if correctness_passed else "test fixture failure",
        scored_at="2026-05-08T00:00:00Z",
    )


_BASE_SPEC = {
    "lang_name": "alpha",
    "display_name": "alpha",
    "options": {"syntax": "c_like", "typing": "dynamic", "memory": "host_gc"},
    "customization": {"persona": None, "era": None, "theme": None,
                      "phrasebook": None, "feature_bans": []},
    "comment_syntax": {"line": "//", "block_open": "/*", "block_close": "*/"},
    "file_extension": ".al",
    "statement_terminator": ";",
    "creative": {"readme_intro": "alpha is a baseline c_like language."},
    "origin_story": "alpha was generated by the test suite.",
}


