def test_fingerprint_ignores_creative_output(tmp_path):
    """Two languages with identical specs but different generated
    origin_stories are NOT duplicates per the documented design choice
    (creative content can be substantively different even when the
    structural spec is identical)."""
    a_dir = tmp_path / "a"
    b_dir = tmp_path / "b"
    spec_a = copy.deepcopy(_BASE_SPEC)
    spec_b = copy.deepcopy(_BASE_SPEC)
    spec_a["origin_story"] = "Story A — short."
    spec_b["origin_story"] = "Story B — completely different content here."
    spec_a["creative"] = {"readme_intro": "Intro A"}
    spec_b["creative"] = {"readme_intro": "Intro B (different)"}
    # Both ALSO need different lang_names so they're distinct test
    # entries (otherwise fingerprint test 1 already passes here).
    spec_a["lang_name"] = "alpha"
    spec_b["lang_name"] = "beta"
    _write_spec(a_dir, spec_a)
    _write_spec(b_dir, spec_b)
    r_a = _make_report(slot_id="a", lang_dir=a_dir)
    r_b = _make_report(slot_id="b", lang_dir=b_dir)
    # Per the design: creative output is excluded from the fingerprint,
    # so these still hash identically.
    assert fingerprint(r_a) == fingerprint(r_b)


def test_fingerprint_handles_missing_spec(tmp_path):
    """If resolved_spec.json is missing, fingerprint should still
    produce a deterministic value (based on slot_id) so dedup doesn't
    crash on a partially-broken language directory."""
    lang_dir = tmp_path / "no_spec"
    lang_dir.mkdir()
    r = _make_report(slot_id="no_spec", lang_dir=lang_dir)
    fp1 = fingerprint(r)
    fp2 = fingerprint(r)
    assert fp1 == fp2  # deterministic
    assert fp1  # non-empty


